    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
if (currentUser == null) {
        JOptionPane.showMessageDialog(
            this,
            "No user is currently logged in.",
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
        return;
    }

    // Get values from the form
    String name = jTextField4.getText().trim();
    String phoneNumber = phone.getText().trim();
    String dateText = jTextField1.getText().trim();
    String service = jComboBox1.getSelectedItem().toString();
    String time = jComboBox2.getSelectedItem().toString();

    // =========================
    // VALIDATION
    // =========================

    if (name.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter your name."
        );
        return;
    }

    if (phoneNumber.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter your phone number."
        );
        return;
    }
    if (!phoneNumber.matches("09\\d{9}")) {

    JOptionPane.showMessageDialog(
        this,
        "Invalid phone number!\n\n"
      + "Phone number must:\n"
      + "• Start with 09\n"
      + "• Have exactly 11 digits\n"
      + "• Contain numbers only",
        "Invalid Phone Number",
        JOptionPane.WARNING_MESSAGE
    );

    return;
}

    if (dateText.isEmpty() || dateText.equals("00/00/00")) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter your appointment date."
        );
        return;
    }

    // =========================
    // CHECK DATE
    // =========================

    try {

        SimpleDateFormat sdf =
                new SimpleDateFormat("MM/dd/yy");

        sdf.setLenient(false);

        Date date = sdf.parse(dateText);

        Calendar calendar = Calendar.getInstance();
        calendar.setTime(date);

        int day = calendar.get(Calendar.DAY_OF_WEEK);

        // No weekends
        if (day == Calendar.SATURDAY ||
            day == Calendar.SUNDAY) {

            JOptionPane.showMessageDialog(
                this,
                "Weekends are unavailable.\n"
              + "Please select a date from Monday to Friday.",
                "Unavailable Date",
                JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        // =========================
        // SAVE TO DATABASE
        // =========================

        // Convert MM/dd/yy to yyyy-MM-dd
        String databaseDate =
                new SimpleDateFormat("yyyy-MM-dd")
                .format(date);

        boolean success =
                AppointmentDAO.bookAppointment(
                    currentUser.getId(),
                    name,
                    phoneNumber,
                    databaseDate,
                    time,
                    service
                );

        if (success) {

            JOptionPane.showMessageDialog(
                this,
                "Appointment booked successfully!",
                "Success",
                JOptionPane.INFORMATION_MESSAGE
            );

            // Clear form
            jTextField4.setText("");
            phone.setText("");
            jTextField1.setText("00/00/00");
            loadAppointments();

            // Go to My Appointments
            jTabbedPane1.setSelectedIndex(2);

        } else {

            JOptionPane.showMessageDialog(
                this,
                "Failed to book appointment.\n"
              + "Please try again.",
                "Booking Error",
                JOptionPane.ERROR_MESSAGE
            );
        }

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
            this,
            "Invalid date.\n"
          + "Please use the format MM/DD/YY.",
            "Invalid Date",
            JOptionPane.ERROR_MESSAGE
        );
    }

    }//GEN-LAST:event_jButton7ActionPerformed

