private void loadAppointments() {

    if (currentUser == null) {
        return;
    }

    DefaultTableModel model =
            (DefaultTableModel) jTable1.getModel();

    // Clear old rows
    model.setRowCount(0);

    ArrayList<Appointment> appointments =
            AppointmentDAO.getAppointments(currentUser.getId());

    for (Appointment appointment : appointments) {

        String status = appointment.getStatus();

        // Show only current appointments
        if (status.equalsIgnoreCase("Pending") ||
            status.equalsIgnoreCase("Approved") ||
            status.equalsIgnoreCase("Accepted")) {

            model.addRow(new Object[]{
                appointment.getAppointmentDate(),
                appointment.getAppointmentTime(),
                appointment.getService(),
                appointment.getStatus()
            });
        }
    }
}

private void loadDentistAppointments() {

    DefaultTableModel model =
            (DefaultTableModel) jTable3.getModel();

    model.setRowCount(0);

    dentistAppointmentIds.clear();

    ArrayList<Appointment> appointments =
            AppointmentDAO.getAllAppointments();

    for (Appointment appointment : appointments) {

        dentistAppointmentIds.add(appointment.getId());

        model.addRow(new Object[]{
            appointment.getPatient(),
            appointment.getAppointmentDate(),
            appointment.getAppointmentTime(),
            appointment.getService(),
            appointment.getPhone(),
            appointment.getStatus()
        });
    }
}
private void setupRoleInterface() {

    if (currentUser == null) {
        return;
    }

    if (currentUser.getRole().equalsIgnoreCase("DENTIST")) {

        // =========================
        // DENTIST INTERFACE
        // =========================

        jButton1.setText("MANAGE APPOINTMENTS");
        jButton3.setText("PATIENTS");

    } else {

        // =========================
        // USER INTERFACE
        // =========================

        jButton1.setText("APPOINT");
        jButton3.setText("MY APPOINTMENTS");
    }
}


    

    




